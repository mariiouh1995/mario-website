import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
process.loadEnvFile('.env.local');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5181';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(base + '/admin', { waitUntil: 'domcontentloaded' });
  await page.getByLabel('Admin-Passwort').fill(process.env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Anmelden', exact: true }).click();
  await page.getByRole('button', { name: 'Website', exact: true }).click({ timeout: 60000 });
  await page.getByLabel('Seite', { exact: true }).selectOption('/tierfotografie');
  const frame = page.frameLocator('iframe[title="Website-Vorschau"]');
  const image = frame.locator('main > section').first().locator('img');
  await image.waitFor({ timeout: 60000 });
  await frame.locator('main > section').first().click({ position: { x: 20, y: 20 } });
  await page.getByRole('group', { name: 'Bildposition Desktop', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Desktop: Oben Mitte', exact: true }).click();
  await expect(image).toHaveCSS('object-position', '50% 0%', { timeout: 15000 });
  await page.getByTitle('Bildposition Mobil', { exact: true }).click();
  await page.getByRole('button', { name: 'Mobil: Mitte rechts', exact: true }).click();
  await expect(image).toHaveCSS('object-position', '100% 50%', { timeout: 15000 });
  await page.getByTitle('Bildposition Desktop', { exact: true }).click();
  assert.equal(await image.evaluate(element => getComputedStyle(element).objectPosition), '50% 0%');
  await page.getByTitle('Automatische Bildposition wiederherstellen', { exact: true }).click();
  await expect(image).toHaveCSS('object-position', '50% 25%', { timeout: 15000 });
  assert.equal(await frame.getByRole('dialog', { name: 'Deine Privatsphäre' }).count(), 0, 'No automatic consent prompt obscures the editor');
  await frame.getByRole('button', { name: 'Cookie-Einstellungen', exact: true }).click();
  await frame.getByRole('dialog', { name: 'Deine Privatsphäre' }).waitFor();
  await frame.getByRole('button', { name: 'Schließen', exact: true }).click();
  await page.screenshot({ path: 'test-results/framing-editor-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false);
  await page.screenshot({ path: 'test-results/framing-editor-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('9-point image positioning verified: desktop/mobile are independent, preview updates, reset and mobile layout work. No draft saved.');
} finally { await browser.close(); }
