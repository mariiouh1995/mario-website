import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from '@playwright/test';
process.loadEnvFile('.env.local');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5181';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await context.newPage();
page.setDefaultNavigationTimeout(60000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await fs.mkdir('test-results/ui-fixed', { recursive: true });
const screenshot = name => page.screenshot({ path: `test-results/ui-fixed/${name}.png` });
const noOverflow = async label => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false, label);
try {
  await page.goto(base + '/hochzeiten', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Alle ablehnen', exact: true }).click();
  const trigger = page.getByRole('button', { name: 'Erzählt mir von euren Plänen', exact: true });
  assert.equal(await trigger.evaluate(el => getComputedStyle(el).borderRadius), '0px', 'Underline has square ends');
  await trigger.click();
  await page.getByRole('dialog', { name: 'Kontaktanfrage' }).waitFor();
  await page.getByLabel('Name', { exact: false }).first().waitFor();
  await page.waitForFunction(() => { let element = document.querySelector('[role=dialog]'); while (element) { if (Number(getComputedStyle(element).opacity) < 0.999) return false; element = element.parentElement; } return true; });
  await screenshot('contact-mobile');
  await noOverflow('Contact form does not overflow');
  for (let i = 0; i < 20; i++) { await page.keyboard.press('Tab'); assert.equal(await page.evaluate(() => Boolean(document.activeElement.closest('[role=dialog]'))), true, 'Contact keyboard focus stays in dialog'); }
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true, 'Contact returns keyboard focus');
  const galleryButton = page.getByRole('button', { name: /^Bild öffnen:/ }).first();
  await galleryButton.click();
  await page.getByRole('dialog', { name: 'Bildergalerie' }).waitFor();
  await page.keyboard.press('ArrowRight');
  await page.getByText(/^2 \/ \d+$/).waitFor();
  await screenshot('lightbox-mobile');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const menu = page.getByRole('button', { name: 'Menü öffnen' });
  await menu.click();
  assert.equal(await page.getByRole('button', { name: 'Menü schließen' }).getAttribute('aria-expanded'), 'true');
  await page.locator('#mobile-navigation').getByRole('link', { name: 'Tierfotografie', exact: true }).click();
  await page.getByRole('button', { name: 'Menü öffnen' }).waitFor();
  console.log('Public interactions verified: CTA shape, contact labels/focus/Escape, keyboard gallery and mobile navigation.');

  await page.goto(base + '/admin', { waitUntil: 'domcontentloaded' });
  await page.getByLabel('Admin-Passwort').fill(process.env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Anmelden', exact: true }).click();
  await page.getByRole('button', { name: 'Website', exact: true }).waitFor({ timeout: 60000 });
  await page.getByText('Lade CRM...', { exact: true }).waitFor({ state: 'hidden', timeout: 60000 });
  for (const width of [360, 640, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.getByRole('button', { name: 'Dashboard', exact: true }).first().click();
    const top = await page.locator('[data-admin-panel]').evaluate(el => el.getBoundingClientRect().top + scrollY);
    assert.ok(top < 800, 'Dashboard content is immediately reachable');
    await page.getByRole('button', { name: 'Benachrichtigungen', exact: true }).click();
    const panel = page.getByRole('region', { name: 'Benachrichtigungen' });
    const rect = await panel.boundingBox();
    assert.ok(rect.x >= 0 && rect.x + rect.width <= width + 1, 'Notifications stay inside screen');
    await screenshot(`notifications-${width}`);
    await page.keyboard.press('Escape');
    await panel.waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Kalender', exact: true }).first().click();
    await noOverflow('Calendar fits viewport');
    await screenshot(`calendar-${width}`);
    await page.getByRole('button', { name: 'Liste anzeigen', exact: true }).first().click();
    await noOverflow('Customer list fits viewport');
    await screenshot(`customers-${width}`);
  }
  await page.getByTitle('Globale Settings').click();
  await page.getByRole('dialog', { name: 'Globale Settings' }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  console.log('Admin verified: immediately visible content, mobile/tablet customer cards, calendar, notifications and modal keyboard controls.');

  await page.getByRole('button', { name: 'Website', exact: true }).click();
  await page.getByRole('button', { name: 'Galerien', exact: true }).click({ timeout: 60000 });
  const select = page.getByLabel('Galerie', { exact: true });
  for (const value of ['hochzeit', 'portrait', 'tiere']) { await select.selectOption(value); assert.ok(await page.locator('[data-gallery-image]').count() > 0); }
  const firstSrc = await page.locator('[data-gallery-image] img').first().getAttribute('src');
  await page.getByTitle('Nach hinten verschieben', { exact: true }).first().click();
  assert.equal(await page.locator('[data-gallery-image] img').nth(1).getAttribute('src'), firstSrc, 'Gallery order updates');
  await page.getByTitle('Bild bearbeiten', { exact: true }).first().click();
  await page.getByLabel('Bildbeschreibung Deutsch').fill('Galerie QA Bild');
  await page.getByRole('button', { name: 'Übernehmen', exact: true }).click();
  const changedSrc = await page.locator('[data-gallery-image] img').first().getAttribute('src');
  await screenshot('gallery-desktop');
  await page.getByTitle('Aus Galerie entfernen', { exact: true }).first().click();
  await page.getByRole('dialog').getByRole('button', { name: 'Aus Galerie entfernen', exact: true }).click();
  assert.notEqual(await page.locator('[data-gallery-image] img').first().getAttribute('src'), changedSrc);
  await page.getByRole('button', { name: 'Bilder hinzufügen', exact: true }).click();
  await page.locator('.cms-gallery-picker-grid .cms-medium').first().click();
  await page.getByRole('button', { name: '1 Bilder hinzufügen', exact: true }).click();
  await page.getByTitle('Bild austauschen', { exact: true }).first().click();
  await page.locator('.cms-gallery-picker-grid .cms-medium').first().click();
  const replacement = await page.locator('.cms-gallery-picker-grid .cms-medium[aria-pressed=true] img').getAttribute('src');
  await page.getByRole('button', { name: 'Bild übernehmen', exact: true }).click();
  assert.equal(await page.locator('[data-gallery-image] img').first().getAttribute('src'), replacement);
  await page.getByTitle('Bild bearbeiten', { exact: true }).first().click();
  await page.getByLabel('Bildbeschreibung Deutsch').fill('Galerie QA Bild');
  await page.getByRole('button', { name: 'Übernehmen', exact: true }).click();
  await page.setViewportSize({ width: 360, height: 844 });
  await screenshot('gallery-mobile');
  await noOverflow('Gallery management fits mobile');
  await page.getByRole('button', { name: 'Seitenvorschau', exact: true }).click();
  await page.getByLabel('Seite', { exact: true }).selectOption('/tierfotografie');
  const frame = page.frameLocator('iframe[title="Website-Vorschau"]');
  await frame.getByRole('button', { name: 'Bild öffnen: Galerie QA Bild', exact: true }).waitFor({ timeout: 60000 });
  assert.equal(await frame.getByRole('button', { name: 'Bild öffnen: Galerie QA Bild', exact: true }).locator('img').getAttribute('src'), replacement, 'Animal gallery renders editor changes');
  console.log('Galleries verified: all galleries available; order, descriptions, removal, adding, replacement and live preview. Nothing saved or published.');
  assert.deepEqual(errors, []);
} catch (error) { await screenshot('failure').catch(() => {}); console.log('Runtime errors:', errors); throw error; }
finally { await browser.close(); }
