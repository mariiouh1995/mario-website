import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { del } from '@vercel/blob';
process.loadEnvFile('.env.local');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5180';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
if (process.env.TEST_VERCEL_BYPASS) await context.route(base + '/**', route => route.continue({ headers: { ...route.request().headers(), 'x-vercel-protection-bypass': process.env.TEST_VERCEL_BYPASS } }));
const page = await context.newPage();
console.log('Browser started');
const errors = [];
const requests = [];
let uploadedUrl;
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => requests.push(request.url()));
page.on('response', response => { if (response.url().includes('/api/website')) console.log('Website API status:', response.status(), new URL(response.url()).search); });
await fs.mkdir('test-results', { recursive: true });
try {
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  console.log('Home loaded');
  await page.getByRole('button', { name: 'Alle ablehnen', exact: true }).click({ timeout: 60000 });
  await page.screenshot({ path: 'test-results/home-desktop.png' });
  assert.equal(requests.filter(url => /googletagmanager|google-analytics|youtube(?:-nocookie)?\.com/.test(url)).length, 0, 'No optional third parties before consent');
  await page.goto(base + '/hochzeiten', { waitUntil: 'domcontentloaded' });
  await page.getByText('Auf Anfrage', { exact: true }).first().waitFor();
  assert.equal(/spieglein|fotospiegel/i.test(await page.locator('body').innerText()), false);
  await page.screenshot({ path: 'test-results/weddings-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/weddings-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false, 'No mobile overflow');
  console.log('Public pages checked');
  await page.goto(base + '/admin', { waitUntil: 'domcontentloaded' });
  await page.locator('input[type=password]').fill(process.env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Anmelden', exact: true }).click();
  await page.getByRole('button', { name: 'Website', exact: true }).click({ timeout: 60000 });
  await page.setViewportSize({ width: 1440, height: 1000 });
  const frame = page.frameLocator('iframe[title="Website-Vorschau"]');
  await frame.locator('h1').first().waitFor({ timeout: 60000 });
  await frame.locator('section').first().locator('p').first().click();
  await page.getByRole('textbox', { name: 'Text', exact: true }).first().waitFor();
  const field = page.getByRole('textbox', { name: 'Text', exact: true }).first();
  const original = await field.inputValue();
  await field.fill('CMS Vorschau Test');
  await frame.getByText('CMS Vorschau Test', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/editor-desktop.png' });
  await field.fill(original);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/editor-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false, 'Editor no mobile overflow');
  await page.getByLabel('Seite', { exact: true }).selectOption('/hochzeiten');
  await frame.locator('h1').first().waitFor();
  await page.getByTitle('Seite bedienen', { exact: true }).click();
  await frame.getByRole('button', { name: /^videos$/i }).click();
  await page.getByTitle('Inhalte auswählen', { exact: true }).click();
  await frame.locator('[data-cms-video-src]').first().click();
  const videoField = page.getByRole('textbox', { name: 'Bild / Video', exact: true });
  const originalVideo = await videoField.inputValue();
  await videoField.fill('https://youtu.be/aD9G344Yt_o');
  await frame.locator('[data-cms-video-src="https://youtu.be/aD9G344Yt_o"]').waitFor();
  assert.ok(await frame.getByRole('button', { name: /^videos$/i }).isVisible(), 'Editing keeps the selected gallery tab');
  await videoField.fill(originalVideo);
  await page.getByRole('button', { name: 'Medien', exact: true }).click();
  const filename = 'website-qa-' + Date.now() + '.png';
  await page.locator('input[type="file"]').setInputFiles({ name: filename, mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aMEcAAAAASUVORK5CYII=', 'base64') });
  await Promise.race([
    page.getByText('Medium hochgeladen', { exact: true }).waitFor({ timeout: 60000 }),
    page.locator('[data-sonner-toast][data-type="error"]').first().waitFor({ timeout: 60000 }).then(async () => { throw new Error(await page.locator('[data-sonner-toast][data-type="error"]').first().innerText()); }),
  ]);
  await page.getByPlaceholder('Medien suchen').fill(filename);
  uploadedUrl = await page.locator('.cms-medium img').first().getAttribute('src');
  assert.equal((await fetch(uploadedUrl)).status, 200, 'Uploaded media is available');
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: cookies rejected, public packages, no Spieglein, mobile layout, admin login, inline text editing and Blob media upload.');
} catch (error) {
  await page.screenshot({ path: 'test-results/failure.png' }).catch(() => {});
  console.log('Runtime errors:', errors);
  console.log('CMS errors:', await page.locator('.cms-error,.cms-loading').allTextContents());
  throw error;
} finally { if (uploadedUrl) await del(uploadedUrl, { token: process.env.BLOB_READ_WRITE_TOKEN }); await browser.close(); }
